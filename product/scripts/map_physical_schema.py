# Motadata role → required Arrow plain type
ROLE_ARROW_PLAIN = {
    "id": "Utf8",
    "string": "Utf8",
    "enum_like": "Utf8",
    "promoted_tag": "Utf8",
    "epoch_ms": "UInt64",
    "snowflake": "UInt64",
    "u32": "UInt32",
}


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def json_prop_nullability(prop: dict[str, Any]) -> bool:
    """True if JSON Schema allows null."""
    t = prop.get("type")
    if isinstance(t, list):
        return "null" in t
    if "const" in prop:
        return False
    return False


def json_prop_types(prop: dict[str, Any]) -> list[str]:
    if "const" in prop:
        return ["const"]
    t = prop.get("type")
    if isinstance(t, list):
        return sorted(t)
    if isinstance(t, str):
        return [t]
    return []


def normalize_types(types: list[str]) -> list[str]:
    return sorted(types)


def arrow_dtype_rust(plain: str, use_dict: bool) -> str:
    if use_dict:
        if plain != "Utf8":
            raise ValueError(f"dictionary only supported for Utf8, got {plain}")
        return (
            "DataType::Dictionary(Box::new(DataType::Int32), Box::new(DataType::Utf8))"
        )
    return f"DataType::{plain}"


def field_rust(name: str, plain: str, nullable: bool, use_dict: bool) -> str:
    dtype = arrow_dtype_rust(plain, use_dict)
    null_lit = "true" if nullable else "false"
    if dtype.startswith("DataType::Dictionary"):
        return (
            f'        Field::new(\n'
            f'            "{name}",\n'
            f"            {dtype},\n"
            f"            {null_lit},\n"
            f"        ),"
        )
    return f'        Field::new("{name}", {dtype}, {null_lit}),'


def generate_schema_rs(node: dict[str, Any], edge: dict[str, Any]) -> str:
    """Render pillar-b/map-vortex/src/schema.rs from physical overlays."""
    lines: list[str] = [
        "// @generated by scripts/generate_map_arrow_schema.py — DO NOT EDIT BY HAND.",
        "// Source: contracts/schemas/graph_node_v1.physical.json",
        "//         contracts/schemas/graph_edge_v1.physical.json",
        "// Regenerate: make generate-map-arrow-schema",
        "",
        "//! Arrow schemas for ``map_nodes`` and ``map_edges`` (vortex_s3 Motadata physical).",
        "",
        "use arrow::datatypes::{DataType, Field, Schema};",
        "use std::sync::Arc;",
        "",
    ]

    def emit_columns_const(prefix: str, overlay: dict[str, Any]) -> None:
        names = [c["name"] for c in overlay["columns"]]
        lines.append(f"pub const {prefix}_COLUMNS: &[&str] = &[")
        for n in names:
            lines.append(f'    "{n}",')
        lines.append("];")
        lines.append("")

    emit_columns_const("NODE", node)
    emit_columns_const("EDGE", edge)

    lines.append("/// Walk projection — defer promoted tags and clocks.")
    lines.append("pub const NODE_WALK_COLUMNS: &[&str] = &[")
    for n in node["walk_columns"]:
        lines.append(f'    "{n}",')
    lines.append("];")
    lines.append("")
    lines.append("/// Walk projection — defer ``evidence_event_id``.")
    lines.append("pub const EDGE_WALK_COLUMNS: &[&str] = &[")
    for n in edge["walk_columns"]:
        lines.append(f'    "{n}",')
    lines.append("];")
    lines.append("")

    attr = node.get("attr_catalog") or "attr_catalog.v1"
    lines.append("/// Promoted tag catalog version stamped on schema metadata.")
    lines.append(f'pub const ATTR_CATALOG_VERSION: &str = "{attr}";')
    lines.append("")

    lines.append("fn node_metadata() -> std::collections::HashMap<String, String> {")
    lines.append("    [")
    lines.append('        ("observeops.table".into(), "map_nodes".into()),')
    lines.append(
        f'        ("observeops.schema_version".into(), "{node["observeops_schema_version"]}".into()),'
    )
    lines.append('        ("observeops.attr_catalog".into(), ATTR_CATALOG_VERSION.into()),')
    lines.append("    ]")
    lines.append("    .into_iter()")
    lines.append("    .collect()")
    lines.append("}")
    lines.append("")

    lines.append("fn edge_metadata() -> std::collections::HashMap<String, String> {")
    lines.append("    [")
    lines.append('        ("observeops.table".into(), "map_edges".into()),')
    lines.append(
        f'        ("observeops.schema_version".into(), "{edge["observeops_schema_version"]}".into()),'
    )
    lines.append("    ]")
    lines.append("    .into_iter()")
    lines.append("    .collect()")
    lines.append("}")
    lines.append("")

    def emit_schema_fn(fn_name: str, overlay: dict[str, Any], *, dict_mode: bool, meta: str, doc: str) -> None:
        lines.append(f"/// {doc}")
        lines.append(f"pub fn {fn_name}() -> Schema {{")
        lines.append("    let fields = vec![")
        for col in overlay["columns"]:
            use_dict = bool(dict_mode and col.get("arrow_dict"))
            plain = col["arrow_plain"]
            lines.append(field_rust(col["name"], plain, col["nullable"], use_dict))
        lines.append("    ];")
        lines.append(f"    Schema::new_with_metadata(fields, {meta}())")
        lines.append("}")
        lines.append("")

    emit_schema_fn(
        "map_nodes_schema",
        node,
        dict_mode=True,
        meta="node_metadata",
        doc="Arrow schema for ``map_nodes`` (dictionary on ``type`` + promoted tags).",
    )
    emit_schema_fn(
        "map_edges_schema",
        edge,
        dict_mode=True,
        meta="edge_metadata",
        doc="Arrow schema for ``map_edges`` (dictionary on ``edge_type``).",
    )
    emit_schema_fn(
        "map_nodes_schema_plain",
        node,
        dict_mode=False,
        meta="node_metadata",
        doc="Plain Utf8 schemas (no dictionary) — Vortex write path today.",
    )
    emit_schema_fn(
        "map_edges_schema_plain",
        edge,
        dict_mode=False,
        meta="edge_metadata",
        doc="Plain Utf8 edge schema (no dictionary) — Vortex write path today.",
    )

    lines.append("pub fn map_nodes_schema_arc() -> Arc<Schema> {")
    lines.append("    Arc::new(map_nodes_schema())")
    lines.append("}")
    lines.append("")
    lines.append("pub fn map_edges_schema_arc() -> Arc<Schema> {")
    lines.append("    Arc::new(map_edges_schema())")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def check_role_rules(col: dict[str, Any], errors: list[str], label: str) -> None:
    role = col.get("role")
    plain = col.get("arrow_plain")
    expected = ROLE_ARROW_PLAIN.get(role)
    if expected is None:
        errors.append(f"{label}.{col['name']}: unknown role {role!r}")
        return
    if plain != expected:
        errors.append(
            f"{label}.{col['name']}: role {role} requires arrow_plain={expected}, got {plain}"
        )


def check_logical_vs_physical(
    logical: dict[str, Any],
    physical: dict[str, Any],
    errors: list[str],
) -> None:
    label = physical["logical_schema"]
    envelope = set(physical.get("envelope_only_fields") or [])
    props = logical.get("properties") or {}
    required = set(logical.get("required") or [])

    logical_cold = sorted(set(props) - envelope)
    physical_names = [c["name"] for c in physical["columns"]]
    if logical_cold != sorted(physical_names):
        errors.append(
            f"{label}: cold fields mismatch\n"
            f"  JSON Schema: {logical_cold}\n"
            f"  physical:    {sorted(physical_names)}"
        )

    phys_by_name = {c["name"]: c for c in physical["columns"]}
    for name in logical_cold:
        prop = props[name]
        col = phys_by_name.get(name)
        if col is None:
            continue
        json_nullable = json_prop_nullability(prop)
        if json_nullable != col["nullable"]:
            errors.append(
                f"{label}.{name}: nullability JSON={json_nullable} physical={col['nullable']}"
            )
        # Required cold fields must be non-null in physical
        if name in required and col["nullable"]:
            errors.append(f"{label}.{name}: required in JSON Schema but physical nullable=true")

        jt = normalize_types(json_prop_types(prop))
        # strip null for comparison to declared json_types without forcing order issues
        declared = normalize_types(col.get("json_types") or [])
        if jt != declared:
            errors.append(
                f"{label}.{name}: json_types overlay={declared} schema={jt}"
            )

        check_role_rules(col, errors, label)

    for walk in physical.get("walk_columns") or []:
        if walk not in phys_by_name:
            errors.append(f"{label}: walk_columns has unknown field {walk!r}")
